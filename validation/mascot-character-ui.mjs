  await economy.addInitScript(({conversationId,projectId})=>{localStorage.setItem('hydraq.conversation',conversationId);localStorage.setItem('hydraq.project',projectId);},{conversationId:conversation.id,projectId:project.id});
  await economy.goto(url);
  await economy.locator('.mascot-svg').waitFor({timeout:20000});
