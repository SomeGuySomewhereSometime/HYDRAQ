  check('abrir na margem esquerda mantém posição horizontal da mascote',near(leftOpen.x,leftClosed.x));
  await launcher.click();
  await launcher.click(); await panel.waitFor();
  const openPosition=await launcher.boundingBox();
  await page.mouse.move(openPosition.x+openPosition.width/2,openPosition.y+openPosition.height/2);
  await page.mouse.down(); await page.mouse.move(50,900,{steps:12}); await page.mouse.up();
  const openMoved=await launcher.boundingBox(), openPanel=await panel.boundingBox();
  check('arrastar com painel aberto mantém os dois visíveis',await launcher.getAttribute('aria-expanded')==='true' && await panel.isVisible() && await character.isVisible() && openMoved.x>=0 && openPanel.x>=0 && openPanel.y>=0);
  await page.emulateMedia({reducedMotion:'reduce'});
  check('movimento reduzido desativa todas as animações da Faísca',await svg.evaluate(el=>el.getAnimations({subtree:true}).length===0));
  await page.setViewportSize({width:390,height:844});
  await page.waitForFunction(()=>{const r=document.querySelector('#companion-launcher').getBoundingClientRect();return r.right<=innerWidth && r.bottom<=innerHeight;});
  const mobileMascot=await launcher.boundingBox(), mobilePanel=await panel.boundingBox();
  check('mascote permanece dentro dos limites no telemóvel',mobileMascot.x>=0 && mobileMascot.y>=0 && mobileMascot.x+mobileMascot.width<=390 && mobileMascot.y+mobileMascot.height<=844);
  check('painel aberto cabe no telemóvel',mobilePanel.x>=0 && mobilePanel.y>=0 && mobilePanel.x+mobilePanel.width<=390 && mobilePanel.y+mobilePanel.height<=844);
  check('mascote continua visível com o painel aberto no telemóvel',await character.isVisible() && await panel.isVisible());
  await page.screenshot({path:'/tmp/hydraq-mascot-mobile.png'});
  await page.setViewportSize({width:390,height:430});
  const shortPanel=await panel.boundingBox(),shortMascot=await launcher.boundingBox();
  check('janela baixa mantém painel e mascote dentro do ecrã',shortPanel.y>=0 && shortMascot.y+shortMascot.height<=430);
