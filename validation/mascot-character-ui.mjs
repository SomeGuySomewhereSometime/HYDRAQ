  check('patas caminham em fases distintas',changed('Walk','Leg_0_Upper') && changed('Walk','Leg_1_Upper') && differs(anatomy.measurements.Walk.Leg_0_Upper,anatomy.measurements.Walk.Leg_1_Upper));
  check('osso ocular tem movimento no rig',changed('Idle','EyePivot_0_L'));
  check('pata mantém altura durante a fase de apoio', Math.max(...anatomy.planted.map(p=>p[1])) - Math.min(...anatomy.planted.map(p=>p[1])) < .025);
  check('apoio desloca-se contra o avanço com velocidade uniforme', Math.abs((anatomy.planted[2][2]-anatomy.planted[0][2])/.4 + .443) < .06);
  check('estado recolhido mostra apenas mascote',await launcher.getAttribute('aria-expanded')==='false' && await character.isVisible() && !(await panel.isVisible()) && await launcher.evaluate(el=>getComputedStyle(el.querySelector('.companion-launcher-label')).clipPath==='inset(50%)'));
