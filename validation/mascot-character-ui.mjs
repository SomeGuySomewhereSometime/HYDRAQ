  await page.waitForFunction(()=>Number(getComputedStyle(document.querySelector('.mascot-svg .heart')).opacity)>=.89);
  check('interação ao passar o rato',await svg.locator('.heart').evaluate(el=>Number(getComputedStyle(el).opacity)>=.89));
  await character.click(); await panel.waitFor();
  check('clique abre o painel e mantém a mascote',await panel.isVisible() && await character.isVisible() && await launcher.getAttribute('aria-expanded')==='true');
  const panelRect=await panel.boundingBox(), openRect=await launcher.boundingBox();
  check('painel e personagem estão no ecrã',panelRect.y>=0 && panelRect.x>=0 && panelRect.x+panelRect.width<=1440 && openRect.y+openRect.height<=1000);
  await page.screenshot({path:'/tmp/hydraq-mascot-desktop.png'});
  await character.click();
  check('clique fecha o painel',!(await panel.isVisible()) && await launcher.getAttribute('aria-expanded')==='false');
  await launcher.focus(); await page.keyboard.press('Enter'); await panel.waitFor();
  check('teclado Enter abre a mascote',await launcher.getAttribute('aria-expanded')==='true' && await character.isVisible());
  await launcher.focus(); await page.keyboard.press('Space');
  check('teclado Espaço fecha a mascote',await launcher.getAttribute('aria-expanded')==='false' && !(await panel.isVisible()));
  const before=await launcher.boundingBox();
  await page.mouse.move(before.x+before.width/2,before.y+before.height/2);
  await page.mouse.down(); await page.mouse.move(before.x-200,before.y-180,{steps:15}); await page.mouse.up();
  const moved=await launcher.boundingBox();
  check('arrastar desloca a personagem',Math.abs(moved.x-before.x)>90 && Math.abs(moved.y-before.y)>90);
  check('arrastar não abre o painel',await launcher.getAttribute('aria-expanded')==='false' && !(await panel.isVisible()));
  const saved=await page.evaluate(()=>JSON.parse(localStorage.getItem('hydraq.mascot.position')));
  check('posição guardada em coordenadas relativas',saved.x>0 && saved.x<1 && saved.y>0 && saved.y<1);
  await page.reload(); await character.waitFor();
  await page.waitForFunction(()=>Boolean(document.querySelector('.companion-root')?.style.left));
  const restored=await launcher.boundingBox();
  check('posição restaurada após recarregar',near(restored.x,moved.x) && near(restored.y,moved.y));
  await page.mouse.move(restored.x+restored.width/2,restored.y+restored.height/2);
  await page.mouse.down(); await page.mouse.move(20+restored.width/2,restored.y+restored.height/2,{steps:15}); await page.mouse.up();
  const leftClosed=await launcher.boundingBox();
  check('mascote pode ser movida até à margem esquerda',leftClosed.x>=0 && leftClosed.x<30);
