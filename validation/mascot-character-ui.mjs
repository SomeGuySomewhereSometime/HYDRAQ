  claudeConversation.turns[0].status='completed';
  clients.claude.changed();
  await page.waitForFunction(()=>document.querySelector('.mascot-character')?.dataset.status==='offline');
  check('terminar o trabalho devolve a Faísca à pose de repouso',!(await svg.locator('.signal').isVisible()));
