  const oldRoutes = ['/mascot-hydra.glb','/mascot-hydra.png','/vendor/three.module.min.js'];
  check('ficheiros antigos não são pedidos nem servidos',oldAssets.length===0 && (await Promise.all(oldRoutes.map(route=>page.request.get(url+route)))).every(response=>response.status()===404));
  check('estado recolhido mostra apenas mascote',await launcher.getAttribute('aria-expanded')==='false' && await character.isVisible() && !(await panel.isVisible()) && await launcher.evaluate(el=>getComputedStyle(el.querySelector('.companion-launcher-label')).clipPath==='inset(50%)'));
  check('botão com nome acessível',/Abrir mascote/.test(await launcher.getAttribute('aria-label')));
  const claude=await hub.create({projectId:project.id,revision:hub.projects.data.revision,provider:'claude',model:'test'});
