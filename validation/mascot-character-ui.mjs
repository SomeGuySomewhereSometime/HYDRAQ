  const anatomy=await page.evaluate(async()=>{
    const THREE=await import('/vendor/three.module.min.js');
    const {GLTFLoader}=await import('/vendor/GLTFLoader.js');
    const model=await new GLTFLoader().loadAsync('/mascot-hydra.glb');
    const names=model.animations.map(clip=>clip.name);
    const measurements={};
    for(const clip of model.animations) {
      const mixer=new THREE.AnimationMixer(model.scene); mixer.clipAction(clip).play();
      const samples={};
      for(const time of [0,.12,.25,.4,.6,.8,1.1]) {
        mixer.setTime(time);
        for(const name of ['Neck_0_1','Neck_1_1','Head_0','Head_1','Leg_0_Upper','Leg_1_Upper','EyePivot_0_L']) {
          const node=model.scene.getObjectByName(name);
          if(node) (samples[name]??=[]).push(node.quaternion.toArray().map(value=>Number(value.toFixed(5))));
        }
      }
      measurements[clip.name]=Object.fromEntries(Object.entries(samples).map(([name,values])=>[name,values]));
      mixer.stopAllAction();mixer.uncacheRoot(model.scene);
    }
    const gaitMixer = new THREE.AnimationMixer(model.scene);
    gaitMixer.clipAction(model.animations.find(clip => clip.name === 'Walk')).play();
    const planted = [];
    for (const time of [.12, .32, .52, .70]) {
      gaitMixer.setTime(time); model.scene.updateMatrixWorld(true);
      planted.push(model.scene.getObjectByName('Leg_0_Paw').getWorldPosition(new THREE.Vector3()).toArray());
    }
    gaitMixer.stopAllAction(); gaitMixer.uncacheRoot(model.scene);
    return {names,measurements,planted};
  });
