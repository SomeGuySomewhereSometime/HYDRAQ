  const changed=(clip,name)=>new Set(anatomy.measurements[clip][name].map(JSON.stringify)).size>1;
  check('GLB inclui Idle, Walk, Listen e Talk', ['Idle','Walk','Listen','Talk'].every(name=>anatomy.names.includes(name)));
